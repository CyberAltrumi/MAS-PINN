"""Computational-cost figure and appendix tables from bench_scaling.py / bench_time.py outputs.

Run from LV_half_observed:
    python3 ../plotting/plot_cost.py --scaling results/scaling.json --timing results/timing.json --out ../figures
Writes lv_cost.{pdf,png} and cost_tables.tex (LaTeX tables, numbers taken verbatim from the JSON).
"""
import argparse
import json
import math
from pathlib import Path

import numpy as np
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import plot_nature as pn  # rcParams, colours

MF, DENSE, REF = pn.METHODS['falm'][1], '#30343B', '#9AA0A6'


def panel(ax, letter, title, ylabel):  # letter/title unused: given in the caption
    ax.set_xscale('log', base=2); ax.set_yscale('log')
    ax.set_xlabel('Number of agents $N$'); ax.set_ylabel(ylabel)
    ax.grid(axis='both', color=pn.GRID, linewidth=0.5)


def ref_line(ax, N0, y0, p, Nmax, label, dy=1.0):
    n = np.array([N0, Nmax]); ax.plot(n, y0 * (n / N0) ** p * dy, ':', color=REF, lw=0.8, zorder=1)
    ax.text(Nmax, y0 * (Nmax / N0) ** p * dy, label, color=REF, fontsize=7, ha='left', va='center')


def fig_cost(rows, timing, out):
    N_rows = sorted([r for r in rows if r['axis'] == 'N'], key=lambda r: r['N'])
    N = np.array([r['N'] for r in N_rows])
    mf_t = np.array([r['mf_lm_s'] for r in N_rows]); mf_m = 1e3 * np.array([r['mf_lm_peak_GB'] for r in N_rows])
    dn = [r for r in N_rows if r.get('dense_lm_peak_GB') and not math.isnan(r['dense_lm_peak_GB'])]
    Nd = np.array([r['N'] for r in dn]); d_t = np.array([r['dense_lm_s_per100'] for r in dn]); d_m = 1e3 * np.array([r['dense_lm_peak_GB'] for r in dn])

    w_mm, h_mm = 120, 43
    fig = plt.figure(figsize=(w_mm / 25.4, h_mm / 25.4))
    left, right, bottom, top, gutter = 15, 12, 11, 3, 17
    pw = (w_mm - left - right - gutter) / 2; ph = h_mm - top - bottom
    axes = [fig.add_axes([(left + i * (pw + gutter)) / w_mm, bottom / h_mm, pw / w_mm, ph / h_mm]) for i in range(2)]

    ax = axes[0]; panel(ax, 'a', 'LM solve time', 'Runtime (s)')
    ax.plot(N, mf_t, '-o', color=MF, lw=1.4, ms=4, label='Matrix-free (CG 100)')
    ax.plot(Nd, d_t, '--s', color=DENSE, lw=1.2, ms=3.8, label='Dense normal matrix')
    ref_line(ax, 32, mf_t[N == 32][0], 1, 256, r'$\propto N$', dy=0.55)
    ref_line(ax, 8, d_t[Nd == 8][0], 3, 16, r'$\propto N^3$', dy=0.4)
    ax.set_ylim(1, 3e4)

    ax = axes[1]; panel(ax, 'b', 'LM solve memory', 'Peak memory (MB)')
    ax.plot(N, mf_m, '-o', color=MF, lw=1.4, ms=4)
    ax.plot(Nd, d_m, '--s', color=DENSE, lw=1.2, ms=3.8)
    ref_line(ax, 8, mf_m[N == 8][0], 1, 256, r'$\propto N$', dy=0.45)
    ref_line(ax, 4, d_m[Nd == 4][0], 2, 16, r'$\propto N^2$', dy=0.3)
    ax.axhline(24e3, color=REF, lw=0.8, ls='-'); ax.text(256, 24e3 / 1.15, '24 GB GPU', color=REF, fontsize=7, ha='right', va='top')
    oom = d_m[-1] * (32 / Nd[-1]) ** 2  # N^2 extrapolation of the last dense point
    ax.plot([32], [oom], marker='x', color=DENSE, ms=5, ls='none'); ax.text(32, oom * 1.3, 'out of memory', fontsize=7, color=DENSE, ha='center', va='bottom')
    ax.set_ylim(1, 4e5)
    for ax in axes:
        ax.set_xticks(N); ax.set_xticklabels([str(n) for n in N]); ax.minorticks_off()
    axes[0].legend(loc='upper left', handlelength=2.2)
    fig.savefig(out / 'lv_cost.pdf'); fig.savefig(out / 'lv_cost.png', dpi=600)


def tables(rows, timing, path):
    t = timing; mb = lambda g: f"{1e3 * g:.0f}"
    L = [r"% generated by plot_cost.py from results/timing.json and results/scaling.json", "",
         r"\begin{table}[htbp]", r"\centering",
         r"\caption{Wall-clock time and peak GPU memory per 100 outer iterations at the paper setting ($N=8$, $N_f=1600$, $P=129$), seed 2026, fp64, RTX 4090. ``LM'' is the coefficient update; ``total'' adds the Adam, basis, parameter and loss evaluations.}",
         r"\label{tab:cost-lv}", r"\small", r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
         r"Coefficient solver & LM (s) & Total (s) & Peak memory (MB)\\", r"\midrule"]
    for k, name in [('falm_cg30', 'Matrix-free, 30 CG iterations'), ('falm_cg60', 'Matrix-free, 60 CG iterations'), ('falm_cg100', 'Matrix-free, 100 CG iterations'), ('dense', 'Dense normal matrix, Cholesky')]:
        L.append(f"{name} & {t[k]['lm']:.2f} & {t[k]['total']:.2f} & {mb(t[k]['peak_mem_GB'])}\\\\")
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}", "",
          r"\begin{table}[htbp]", r"\centering",
          r"\caption{One-factor-at-a-time scaling of the coefficient update (LM step, 100 outer iterations). Other factors are held at the paper setting. Matrix-free: time of one operator application $\tilde J^\top\tilde J v$, LM time, and peak memory of the LM step. Dense: LM time and peak memory; ``---'' marks settings exceeding the 24\,GB GPU memory.}",
          r"\label{tab:scaling-lv}", r"\small", r"\begin{tabular}{@{}llrrrrr@{}}", r"\toprule",
          r"& & \multicolumn{3}{c}{Matrix-free} & \multicolumn{2}{c}{Dense}\\", r"\cmidrule(lr){3-5}\cmidrule(lr){6-7}",
          r"Factor & Value & Op. (ms) & LM (s) & Mem. (MB) & LM (s) & Mem. (MB)\\"]
    MED = dict(N=8, N_f=1600, P=129, cg=100)
    for name, key in [('$N$', 'N'), ('$N_f$', 'N_f'), ('$P$', 'P'), ('CG iterations', 'cg')]:
        L.append(r"\midrule")
        block = {r[key]: r for r in rows if all(r[k] == v for k, v in MED.items() if k != key)}  # one row per value, other factors at paper setting
        for r in sorted(block.values(), key=lambda r: r[key]):
            ok = r.get('dense_lm_peak_GB') is not None and not math.isnan(r['dense_lm_peak_GB'])
            dense = "n/a & n/a" if key == 'cg' and r['cg'] != 100 else f"{r['dense_lm_s_per100']:.1f} & {mb(r['dense_lm_peak_GB'])}" if ok else "--- & ---"
            L.append(f"{name} & {r[key]} & {r['op_ms']:.2f} & {r['mf_lm_s']:.2f} & {1e3 * r['mf_lm_peak_GB']:.1f} & {dense}\\\\")
            name = ''
    L += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    path.write_text('\n'.join(L) + '\n')


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--scaling', type=Path, default=Path('results/scaling.json'))
    ap.add_argument('--timing', type=Path, default=Path('results/timing.json'))
    ap.add_argument('--out', type=Path, default=Path('../figures'))
    a = ap.parse_args()
    rows, timing = json.load(open(a.scaling)), json.load(open(a.timing))
    a.out.mkdir(parents=True, exist_ok=True)
    fig_cost(rows, timing, a.out)
    tables(rows, timing, a.out / 'cost_tables.tex')
    print('wrote', a.out / 'lv_cost.pdf', a.out / 'cost_tables.tex')
